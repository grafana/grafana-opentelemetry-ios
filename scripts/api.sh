#!/usr/bin/env bash
# Compares the package's public API with the committed snapshot.
#
#   scripts/api.sh check   fail if the public API differs from api/GrafanaOpenTelemetryIOS.swiftinterface
#   scripts/api.sh dump    rewrite the snapshot after an intentional API change
#
# The snapshot is the module's textual interface without private members and compiler headers.
# It is printed by the compiler, so generate it with the Xcode version that CI uses for this check.
set -euo pipefail

mode="${1:-check}"
if [[ "$mode" != "check" && "$mode" != "dump" ]]; then
  echo "Usage: $0 [check|dump]" >&2
  exit 2
fi

root="$(cd "$(dirname "$0")/.." && pwd)"
snapshot="$root/api/GrafanaOpenTelemetryIOS.swiftinterface"
scratch="$root/.build/api"

# Library evolution is off because upstream dependencies do not compile with it. The interface
# therefore also lists private stored properties, which are removed below.
swift build \
  --package-path "$root" \
  --scratch-path "$scratch" \
  --configuration release \
  --product GrafanaOpenTelemetryIOS \
  --enable-parseable-module-interfaces \
  --quiet

# Where the interface lands depends on the SwiftPM build system, and some write it twice.
interfaces=()
while IFS= read -r -d '' file; do
  interfaces+=("$file")
done < <(find "$scratch" -name "GrafanaOpenTelemetryIOS.swiftinterface" -print0)
if [[ "${#interfaces[@]}" -eq 0 ]]; then
  echo "The build did not write GrafanaOpenTelemetryIOS.swiftinterface" >&2
  exit 1
fi
for file in "${interfaces[@]}"; do
  if ! cmp -s "$file" "${interfaces[0]}"; then
    echo "Found different interfaces: ${interfaces[*]}" >&2
    exit 1
  fi
done

current="$(mktemp)"
trap 'rm -f "$current"' EXIT
{
  echo "// Public API of GrafanaOpenTelemetryIOS. Generated by scripts/api.sh dump; do not edit."
  sed -E \
    -e '/^\/\/ swift-/d' \
    -e '/^[[:space:]]*(@[^ ]+ )*((final|static|lazy|nonisolated) )*(private|fileprivate|internal) /d' \
    "${interfaces[0]}"
} > "$current"

if [[ "$mode" == "dump" ]]; then
  mkdir -p "$(dirname "$snapshot")"
  cp "$current" "$snapshot"
  echo "Wrote $snapshot"
elif ! diff -u "$snapshot" "$current"; then
  echo "The public API differs from $snapshot." >&2
  echo "If the change is intentional, run scripts/api.sh dump and review the snapshot diff." >&2
  exit 1
else
  echo "Public API matches $snapshot"
fi
